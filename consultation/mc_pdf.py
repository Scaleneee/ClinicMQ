"""
consultation/mc_pdf.py
Builds the medical certificate (MC) as an A5 portrait PDF with reportlab (UI.md §5.6, "MC print").
"""

from io import BytesIO

from reportlab.lib.pagesizes import A5
from reportlab.lib.units import mm
from reportlab.lib.utils import simpleSplit
from reportlab.pdfgen import canvas

from queueing.models import ClinicSetting

from .services import mc_end_date

INK = (0.07, 0.07, 0.07)
MUTED = (0.43, 0.43, 0.43)
LINE = (0.80, 0.80, 0.80)
RED = (0.75, 0.22, 0.17)


def _date(d):
    return f"{d:%d/%m/%Y}"


def build_mc_pdf(mc):
    """Return the PDF bytes for a MedicalCertificate."""
    consultation = mc.consultation
    patient = consultation.ticket.patient
    doctor = consultation.doctor
    clinic = ClinicSetting.load()

    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A5)
    pdf.setTitle(f"Medical Certificate {mc.mc_no}")
    pdf.setAuthor(clinic.clinic_name)
    width, height = A5
    left, right = 16 * mm, width - 16 * mm
    y = height - 20 * mm

    # Clinic header
    pdf.setFillColorRGB(*INK)
    pdf.setFont("Times-Bold", 17)
    pdf.drawString(left, y, clinic.clinic_name)
    name_width = pdf.stringWidth(clinic.clinic_name, "Times-Bold", 17)
    pdf.setFillColorRGB(*RED)
    pdf.circle(left + name_width + 2.2 * mm, y + 0.6 * mm, 0.9 * mm, stroke=0, fill=1)
    pdf.setFillColorRGB(*MUTED)
    pdf.setFont("Times-Roman", 9.5)
    contact = " · ".join(part for part in (clinic.address, f"Tel {clinic.phone}" if clinic.phone else "") if part)
    if contact:
        y -= 5 * mm
        for line in simpleSplit(contact, "Times-Roman", 9.5, right - left):
            pdf.drawString(left, y, line)
            y -= 4 * mm
    y -= 4 * mm
    pdf.setStrokeColorRGB(*LINE)
    pdf.line(left, y, right, y)

    # Title and MC number
    y -= 13 * mm
    pdf.setFillColorRGB(*INK)
    pdf.setFont("Times-Roman", 22)
    pdf.drawCentredString(width / 2, y, "Medical Certificate")
    y -= 7 * mm
    pdf.setFillColorRGB(*MUTED)
    pdf.setFont("Times-Roman", 10.5)
    pdf.drawCentredString(width / 2, y, f"MC No. {mc.mc_no}   ·   Issued {_date(mc.issued_at.date())}")

    # Patient details
    y -= 14 * mm
    rows = [
        ("Name", patient.full_name.title()),
        ("IC No.", patient.ic_no),
        ("Visit date", _date(consultation.ticket.queue_date)),
    ]
    for label, value in rows:
        pdf.setFillColorRGB(*MUTED)
        pdf.setFont("Times-Roman", 11)
        pdf.drawString(left, y, label)
        pdf.setFillColorRGB(*INK)
        pdf.setFont("Times-Bold", 11.5)
        pdf.drawString(left + 28 * mm, y, value)
        y -= 7 * mm

    # Statement
    y -= 4 * mm
    end = mc_end_date(mc)
    days = f"{mc.days} day{'s' if mc.days > 1 else ''}"
    period = _date(mc.start_date) if mc.days == 1 else f"{_date(mc.start_date)} to {_date(end)}"
    statement = (f"This is to certify that the above-named patient was examined at this clinic and is "
                 f"unfit for duty for {days}, {'on' if mc.days == 1 else 'from'} {period} (inclusive).")
    pdf.setFillColorRGB(*INK)
    pdf.setFont("Times-Roman", 12)
    for line in simpleSplit(statement, "Times-Roman", 12, right - left):
        pdf.drawString(left, y, line)
        y -= 6 * mm

    y -= 3 * mm
    pdf.setFillColorRGB(*MUTED)
    pdf.setFont("Times-Roman", 11)
    pdf.drawString(left, y, "Reason")
    y -= 5.5 * mm
    pdf.setFillColorRGB(*INK)
    pdf.setFont("Times-Roman", 12)
    for line in simpleSplit(mc.reason, "Times-Roman", 12, right - left):
        pdf.drawString(left, y, line)
        y -= 6 * mm

    # Doctor signature
    sig_y = 38 * mm
    pdf.setStrokeColorRGB(*INK)
    pdf.line(right - 62 * mm, sig_y, right, sig_y)
    pdf.setFont("Times-Bold", 11.5)
    pdf.drawRightString(right, sig_y - 5.5 * mm, f"Dr. {doctor.full_name}")
    pdf.setFillColorRGB(*MUTED)
    pdf.setFont("Times-Roman", 10)
    pdf.drawRightString(right, sig_y - 10 * mm, doctor.specialty or "Medical Officer")
    pdf.drawRightString(right, sig_y - 14.5 * mm, clinic.clinic_name)

    # Footer
    pdf.setStrokeColorRGB(*LINE)
    pdf.line(left, 14 * mm, right, 14 * mm)
    pdf.setFont("Times-Roman", 8.5)
    pdf.drawCentredString(width / 2, 10 * mm,
                          f"This certificate is computer generated by {clinic.clinic_name}. MC No. {mc.mc_no}.")

    pdf.showPage()
    pdf.save()
    return buffer.getvalue()
